"""Built-in prompt profiles, selected with PROMPT_PROFILE.

`call` (default) summarizes a regular two-party phone call coming from BPM.
`voicemail` handles IVR voice messages left while the line is busy: the
summary extracts name / company / e-mail / request in a fixed six-line
template, and the Whisper prompt makes dictated e-mails come out word by word
("… собачка … точка ру"), which the summary prompt then assembles.

SUMMARY_PROMPT / WHISPER_PROMPT override a profile's values. The voicemail
summary keeps the {KNOWN_EMAIL_DOMAINS} placeholder (see config.render_summary_prompt).
"""

CALL_SUMMARY_PROMPT = (
    "Составь краткое содержание телефонного разговора на русском языке: "
    "основная тема, договорённости, следующие шаги. "
    "Отвечай только текстом краткого содержания."
)

